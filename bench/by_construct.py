"""Which SAS constructs trip up which translator?

    python3 bench/by_construct.py      # writes results/by_construct.json and results/BY_CONSTRUCT.md

For every translator and every construct the scanner flags, count the corpus programs that
contain it and how many of those the translator got right. "Right" is the program's
pre-registered result, except where results/overrides.json records a reviewed correction (each
with its reason), for example a comparator error found after the run. Programs that only have a
structure check count as right when they ran and created every expected dataset.
"""

import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from corpus import load_corpus, program_path  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results"


def constructs(prog):
    out = subprocess.run([sys.executable, "-I", str(ROOT / "bench" / "scan.py"), str(program_path(prog))],
                         capture_output=True, text=True, check=True).stdout
    return set(json.loads(out)[0]["constructs"])


def main():
    corpus = load_corpus()
    overrides = json.loads((RES / "overrides.json").read_text()) if (RES / "overrides.json").exists() else {}
    flags = {p["id"]: constructs(p) for p in corpus}
    translators = sorted(d.name for d in RES.iterdir()
                         if d.is_dir() and d.name.split("_")[0] in ("claude-code", "ollama", "anthropic"))
    table, per_program = {}, {}
    for t in translators:
        ok = {}
        for p in corpus:
            f = RES / t / f"{p['id']}.json"
            if not f.exists():
                continue
            r = json.loads(f.read_text())
            o = overrides.get(t, {}).get(p["id"])
            ok[p["id"]] = o["pass"] if o else bool(r.get("pass"))
        per_program[t] = ok
        for c in sorted(set().union(*flags.values())):
            have = [i for i in ok if c in flags[i]]
            table.setdefault(c, {})[t] = {"programs": len(have), "right": sum(ok[i] for i in have)}
    (RES / "by_construct.json").write_text(json.dumps({"per_program": per_program, "by_construct": table}, indent=2) + "\n")

    short = {t: t.replace("claude-code_", "") for t in translators}
    lines = ["# Results by construct", "",
             "Generated by `bench/by_construct.py`. For each construct the scanner flags: right / programs",
             "containing it. Corrections applied after review are listed in `results/overrides.json`.", "",
             "| Construct | " + " | ".join(short[t] for t in translators) + " |",
             "|---|" + "---|" * len(translators)]
    for c, row in sorted(table.items(), key=lambda kv: -max(v["programs"] for v in kv[1].values())):
        lines.append(f"| {c} | " + " | ".join(f"{row[t]['right']} / {row[t]['programs']}" if t in row else "" for t in translators) + " |")
    lines += ["", "| Program | " + " | ".join(short[t] for t in translators) + " |", "|---|" + "---|" * len(translators)]
    for p in corpus:
        lines.append(f"| {p['id']} | " + " | ".join(
            ("yes" if per_program[t][p["id"]] else "no") if p["id"] in per_program[t] else "" for t in translators) + " |")
    (RES / "BY_CONSTRUCT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
