"""Collect results/<translator>/<id>.json into results/summary.json and results/README.md.

Each row joins the run result with the translation sidecar (time, tokens, cost) and the scanner's
construct list for that program, so failures can be read next to the constructs involved.
"""

import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from corpus import load_corpus, program_path  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results"


def scan_constructs(prog):
    out = subprocess.run([sys.executable, "-I", str(ROOT / "bench" / "scan.py"), str(program_path(prog))],
                         capture_output=True, text=True, check=True).stdout
    return sorted(json.loads(out)[0]["constructs"])


def headline(r):
    """One short, factual line per result."""
    if r.get("stage") != "compare":
        return r.get("reason", "")
    if r["id"] == "adae":
        return (f"cell match {r.get('cell_match', 0):.2%}, rows {r.get('rows_got')}/{r.get('rows_ref')}, "
                f"{len(r.get('columns_exact', []))}/{r.get('columns_ref')} columns exact")
    if r["id"] == "at14_5_02":
        return (f"count cells {r.get('count_cells_matched')}/{r.get('count_cells_expected')}, "
                f"p-values produced: {r.get('p_values_found')}")
    if r["id"] == "ae_serious":
        return f"rows matching CSR counts {r.get('rows_matched')}/{r.get('rows_expected')}"
    return r.get("reason", "")


def main():
    corpus = {p["id"]: p for p in load_corpus()}
    rows = []
    for tdir in sorted(p for p in RES.iterdir() if p.is_dir()):
        for f in sorted(tdir.glob("*.json")):
            r = json.loads(f.read_text())
            meta_f = ROOT / "translations" / tdir.name / f"{r['id']}.json"
            meta = json.loads(meta_f.read_text()) if meta_f.exists() else {}
            prog = corpus.get(r["id"], {})
            rows.append({
                "translator": tdir.name, "id": r["id"], "reference": prog.get("reference"),
                "stage": r.get("stage"), "pass": bool(r.get("pass")), "result": headline(r),
                "translate_seconds": meta.get("seconds"), "output_tokens": meta.get("output_tokens"),
                "cost_usd": meta.get("cost_usd"),
                "error_tail": (r.get("stderr_tail") or [])[-2:] if r.get("stage") == "run" else [],
                "constructs": scan_constructs(prog) if prog else [],
            })
    (RES / "summary.json").write_text(json.dumps(rows, indent=2) + "\n")

    lines = ["# Results", "",
             "Generated by `bench/report.py`. Every number comes from a real run of the translation on",
             "the CDISC Pilot data; see `results/<translator>/<id>.json` for the full record.", "",
             "| Translator | Program | Reference | Got to | Pass | Result | Translate time |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        t = f"{r['translate_seconds']}s" if r["translate_seconds"] is not None else ""
        lines.append(f"| {r['translator']} | {r['id']} | {r['reference']} | {r['stage']} | "
                     f"{'yes' if r['pass'] else 'no'} | {r['result']} | {t} |")
    (RES / "README.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
